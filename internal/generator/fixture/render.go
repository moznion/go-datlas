package fixture

import (
	"bytes"
	"fmt"
	"go/types"
	"slices"
	"strconv"
	"strings"

	"github.com/moznion/go-datlas/internal/generator/output"
)

const fixturekitPath = "github.com/moznion/go-datlas/fixturekit"

// identifiers declared or used as locals by the generated code; imports must not shadow them.
var reservedIdents = []string{
	"Option", "WithSeed", "WithClock", "WithNow", "WithTimePrecision", "WithT", "Factory", "New",
	"f", "v", "vs", "i", "n", "opt", "opts", "seed", "clock", "now", "d", "t",
}

// renderer renders the factory methods.
type renderer struct {
	im  *output.Imports
	kit string
	// methods maps each fixture type to the name of its factory method.
	methods map[*types.TypeName]string
}

// render renders the factory. reserved lists identifiers already declared in the output package,
// which imports must not shadow.
func render(pkgName, pkgPath string, fts []FixtureType, reserved []string) ([]byte, error) {
	im := output.NewImports(pkgPath, append(slices.Clone(reservedIdents), reserved...)...)
	kit := im.Add(fixturekitPath, "fixturekit")
	r := &renderer{im: im, kit: kit, methods: map[*types.TypeName]string{}}
	for _, ft := range fts {
		r.methods[ft.Type] = ft.Name
	}
	tm := im.Add("time", "time")

	var b bytes.Buffer
	fmt.Fprintf(&b, `// Option configures a Factory.
type Option = %[1]s.Option

// WithSeed makes the values generated by the Factory deterministic.
// Without it, the seed is read from the %[3]s environment variable or chosen randomly.
func WithSeed(seed uint64) Option { return %[1]s.WithSeed(seed) }

// WithClock sets the clock used for time based values.
func WithClock(clock func() %[2]s.Time) Option { return %[1]s.WithClock(clock) }

// WithNow fixes the current time seen by the Factory.
func WithNow(now %[2]s.Time) Option { return %[1]s.WithNow(now) }

// WithTimePrecision truncates generated times to a multiple of d (default: %[1]s.DefaultTimePrecision).
func WithTimePrecision(d %[2]s.Duration) Option { return %[1]s.WithTimePrecision(d) }

// WithT logs the seed of the Factory when the test fails, so the failure can be reproduced.
func WithT(t %[1]s.TB) Option { return %[1]s.WithT(t) }

// Factory builds test fixtures. It owns the random number generator, the fake data source and the clock.
type Factory struct {
	g *%[1]s.Generator
}

// New returns a new Factory.
func New(opts ...Option) *Factory {
	return &Factory{g: %[1]s.New(opts...)}
}

// Seed returns the seed of the Factory.
func (f *Factory) Seed() uint64 {
	return f.g.Seed()
}

// Faker returns the generator backing the Factory, for ad-hoc fake values.
func (f *Factory) Faker() *%[1]s.Generator {
	return f.g
}
`, kit, tm, "DATLAS_SEED")

	for _, ft := range fts {
		typ := im.TypeString(ft.Type.Type())
		fmt.Fprintf(&b, "\n// %s returns a new %s. opts are applied in order after the fields are generated.\n", ft.Name, typ)
		fmt.Fprintf(&b, "func (f *Factory) %s(opts ...func(*%s)) %s {\n", ft.Name, typ, typ)
		fmt.Fprintf(&b, "v := %s{\n", typ)
		if err := r.writeFields(&b, ft, ft.Fields); err != nil {
			return nil, err
		}
		b.WriteString("}\n")
		if err := r.writePromoted(&b, ft, ft.Fields); err != nil {
			return nil, err
		}
		b.WriteString("for _, opt := range opts {\nopt(&v)\n}\nreturn v\n}\n")

		fmt.Fprintf(&b, "\n// %s returns n new values built by %s.\n", ft.PluralName, ft.Name)
		fmt.Fprintf(&b, "func (f *Factory) %s(n int, opts ...func(*%s)) []%s {\n", ft.PluralName, typ, typ)
		fmt.Fprintf(&b, "vs := make([]%s, n)\n", typ)
		fmt.Fprintf(&b, "for i := range vs {\nvs[i] = f.%s(opts...)\n}\nreturn vs\n}\n", ft.Name)
	}
	return output.File(pkgName, im, b.Bytes()), nil
}

// writeFields renders the initialisers of fields; embedded structs become nested literals.
func (r *renderer) writeFields(b *bytes.Buffer, ft FixtureType, fields []Field) error {
	for _, field := range fields {
		if field.Promoted {
			continue // set by writePromoted
		}
		if field.Children != nil {
			fmt.Fprintf(b, "%s: %s{\n", field.Name, r.im.TypeString(field.Type))
			if err := r.writeFields(b, ft, field.Children); err != nil {
				return err
			}
			b.WriteString("},\n")
			continue
		}
		expr, err := r.fieldExpr(ft, field)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s: %s,\n", field.Name, expr)
	}
	return nil
}

// writePromoted renders assignments to the fields of embedded structs the generated package
// cannot name, e.g. "v.CreatedAt = f.g.Now()", after the composite literal.
func (r *renderer) writePromoted(b *bytes.Buffer, ft FixtureType, fields []Field) error {
	for _, field := range fields {
		switch {
		case field.Promoted:
			for _, leaf := range leaves(field.Children) {
				expr, err := r.fieldExpr(ft, leaf)
				if err != nil {
					return err
				}
				fmt.Fprintf(b, "v.%s = %s\n", leaf.Name, expr)
			}
		case field.Children != nil:
			if err := r.writePromoted(b, ft, field.Children); err != nil {
				return err
			}
		}
	}
	return nil
}

// fieldExpr renders the expression generating the value of field.
func (r *renderer) fieldExpr(ft FixtureType, field Field) (string, error) {
	im, kit := r.im, r.kit
	shape := field.Shape
	expr, err := r.elemExpr(ft, field, shape.Elem)
	if err != nil {
		return "", err
	}
	if w := field.Policy.Wrap; w != nil {
		fn := w.Func.Name()
		if q := im.Add(w.Func.Pkg().Path(), w.Func.Pkg().Name()); q != "" {
			fn = q + "." + fn
		}
		if len(w.TypeArgs) > 0 {
			args := make([]string, len(w.TypeArgs))
			for i, t := range w.TypeArgs {
				args[i] = im.TypeString(t)
			}
			fn += "[" + strings.Join(args, ", ") + "]"
		}
		expr = fn + "(" + expr + ")"
	}
	if shape.Ptr {
		expr = kit + ".Ptr(" + expr + ")"
	}
	if shape.Slice {
		sliceType := im.TypeString(field.Type)
		expr = fmt.Sprintf("func() %s {\nvs := make(%s, %d)\nfor i := range vs {\nvs[i] = %s\n}\nreturn vs\n}()",
			sliceType, sliceType, shape.Count, expr)
	}
	return expr, nil
}

// elemExpr renders the expression generating one value of type t.
func (r *renderer) elemExpr(ft FixtureType, field Field, t types.Type) (string, error) {
	im := r.im
	kind, basic := classify(t)
	p := field.Policy

	var (
		expr string
		// natural is the type of expr before conversion.
		natural types.Type
	)
	str := types.Typ[types.String]
	switch p.Generator {
	case "uuid":
		if kind == kindString {
			expr, natural = "f.g.UUIDString()", str
		} else {
			expr, natural = "f.g.UUID()", types.NewArray(types.Typ[types.Byte], 16)
		}
	case "email", "name", "username", "word", "sentence", "url", "phone":
		expr, natural = "f.g."+goMethod[p.Generator]+"()", str
	case "first_name":
		expr, natural = "f.g.FirstName()", str
	case "last_name":
		expr, natural = "f.g.LastName()", str
	case "alpha", "alphanum":
		n, err := length(p)
		if err != nil {
			return "", err
		}
		expr, natural = fmt.Sprintf("f.g.%s(%d)", goMethod[p.Generator], n), str
	case "int":
		lo, hi, err := intRange(p, kind, basic)
		if err != nil {
			return "", err
		}
		if kind == kindUnsigned {
			expr, natural = fmt.Sprintf("f.g.Uint64Range(%s, %s)", lo, hi), types.Typ[types.Uint64]
		} else {
			expr, natural = fmt.Sprintf("f.g.Int64Range(%s, %s)", lo, hi), types.Typ[types.Int64]
		}
	case "float":
		lo, hi, err := floatRange(p)
		if err != nil {
			return "", err
		}
		expr, natural = fmt.Sprintf("f.g.Float64Range(%s, %s)", lo, hi), types.Typ[types.Float64]
	case "bool":
		expr, natural = "f.g.Bool()", types.Typ[types.Bool]
	case "now", "past", "future":
		expr, natural = "f.g."+goMethod[p.Generator]+"()", t
	case "seq":
		key := strconv.Quote(ft.Type.Pkg().Path() + "." + ft.Type.Name() + "." + field.Name)
		switch kind {
		case kindString:
			sc := im.Add("strconv", "strconv")
			expr, natural = fmt.Sprintf("%s + %s.FormatInt(f.g.Seq(%s), 10)", strconv.Quote(p.Params["prefix"]), sc, key), str
		case kindUnsigned:
			expr, natural = fmt.Sprintf("uint64(f.g.Seq(%s))", key), types.Typ[types.Uint64]
		default:
			expr, natural = fmt.Sprintf("f.g.Seq(%s)", key), types.Typ[types.Int64]
		}
	case "oneof":
		lits, err := oneOfLiterals(p, kind, basic)
		if err != nil {
			return "", err
		}
		expr = fmt.Sprintf("[]%s{%s}[f.g.IntN(%d)]", im.TypeString(t), strings.Join(lits, ", "), len(lits))
		natural = t
	case "enum":
		expr = fmt.Sprintf("[]%s{%s}[f.g.IntN(%d)]", im.TypeString(t), strings.Join(p.Literals, ", "), len(p.Literals))
		natural = t
	case "nested":
		expr, natural = "f."+r.methods[types.Unalias(t).(*types.Named).Obj()]+"()", t
	default:
		return "", fmt.Errorf("unknown fixture generator %q", p.Generator)
	}

	if !types.Identical(natural, t) {
		expr = im.TypeString(t) + "(" + expr + ")"
	}
	return expr, nil
}

var goMethod = map[string]string{
	"email":    "Email",
	"name":     "Name",
	"username": "Username",
	"word":     "Word",
	"sentence": "Sentence",
	"url":      "URL",
	"phone":    "Phone",
	"alpha":    "Alpha",
	"alphanum": "AlphaNum",
	"now":      "Now",
	"past":     "Past",
	"future":   "Future",
}
