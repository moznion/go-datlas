// run generates and writes the factory, returning its path.
func run(cfg Config) (string, error) {
	r, err := Generate(cfg)
	if err != nil {
		return "", err
	}
	if _, err := output.Apply(r, false); err != nil {
		return "", err
	}
	return r.Path, nil
}

func TestGenerate(t *testing.T) {
	dir := testutil.WriteTree(t, map[string]string{
		"model/model.go": modelSrc,
		// A stale factory in the output package must not break regeneration.
		"fx/zz_fixture_gen.go": "// Code generated by datlas. DO NOT EDIT.\n\npackage fx\n\nvar _ = broken\n",
		"fx/use.go":            "package fx\n\nvar _ = New(WithSeed(1)).Everything\n",
	})
	path, err := run(Config{Dir: dir, Patterns: []string{"./..."}, OutDir: "fx"})
	if err != nil {
		t.Fatal(err)
	}
	if path != filepath.Join(dir, "fx", FileName) {
		t.Fatalf("unexpected path %s", path)
	}
	testutil.TypeCheck(t, dir, "./...")
	src := testutil.ReadFile(t, path)
	for _, want := range []string{
		"package fx",
		"ID:      model.ID(f.g.UUID())",
		"IDText:  f.g.UUIDString()",
		"Email:   fixturekit.Ptr(f.g.Email())",
		"Small:   uint8(f.g.Uint64Range(1, 255))",
		"Signed:  int8(f.g.Int64Range(-5, 5))",
		"Big:     f.g.Uint64Range(1, 18446744073709551615)",
		"Score:   model.Score(f.g.Float64Range(0.5, 1.0))",
		`Kind:    []model.Kind{"a", "b"}[f.g.IntN(2)]`,
		"Level:   []int{1, 2, 3}[f.g.IntN(3)]",
		"Future:  fixturekit.Ptr(f.g.Future())",
		"func (f *Factory) Categories(n int, opts ...func(*model.Category)) []model.Category",
	} {
		if !strings.Contains(strings.Join(strings.Fields(src), " "), strings.Join(strings.Fields(want), " ")) {
			t.Errorf("generated code does not contain %q:\n%s", want, src)
		}
	}
	for _, unwanted := range []string{"Untagged", "Skipped", "private"} {
		if strings.Contains(src, unwanted) {
			t.Errorf("generated code sets %s:\n%s", unwanted, src)
		}
	}
}

func TestGenerateIntoSamePackage(t *testing.T) {
	dir := testutil.WriteTree(t, map[string]string{
		"model.go": "package model\n\n//datlas:fixture\ntype user struct {\n\tname string `fixture:\"name\"`\n}\n",
	})
	if _, err := run(Config{Dir: dir, Patterns: []string{"."}, OutDir: "."}); err != nil {
		t.Fatal(err)
	}
	testutil.TypeCheck(t, dir, ".")
}

func TestErrors(t *testing.T) {
	tests := []struct {
		name  string
		field string
		want  string
	}{
		{"unknown generator", "A string `fixture:\"nope\"`", `unknown fixture generator "nope"`},
		{"wrong type", "A int `fixture:\"email\"`", `fixture generator "email" cannot produce a value of type int`},
		{"min greater than max", "A int `fixture:\"int,min=5,max=1\"`", "min 5 is greater than max 1"},
		{"out of range", "A int8 `fixture:\"int,max=1000\"`", `invalid max "1000" for int8`},
		{"unknown parameter", "A string `fixture:\"email,len=3\"`", `does not accept parameter "len"`},
		{"malformed parameter", "A string `fixture:\"alpha,len\"`", "expected key=value"},
		{"oneof without value", "A string `fixture:\"oneof\"`", "requires candidates"},
		{"oneof bad value", "A int `fixture:\"oneof=1|x\"`", `invalid oneof candidate "x"`},
		{"unexported field", "a string `fixture:\"name\"`", "unexported field cannot be set"},
		{"unsupported type", "A map[string]string `fixture:\"word\"`", "cannot produce a value of type map[string]string"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := testutil.WriteTree(t, map[string]string{
				"model/model.go": "package model\n\n//datlas:fixture\ntype T struct {\n\t" + tt.field + "\n}\n\nvar _ = T{}\n",
			})
			_, err := run(Config{Dir: dir, Patterns: []string{"./model"}, OutDir: "fx"})
			if err == nil {
				t.Fatal("expected an error")
			}
			if !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("error %q does not contain %q", err, tt.want)
			}
		})
	}
}

func TestNoFixtures(t *testing.T) {
	dir := testutil.WriteTree(t, map[string]string{"model/model.go": "package model\n\ntype T struct{}\n"})
	_, err := run(Config{Dir: dir, Patterns: []string{"./model"}, OutDir: "fx"})
	if err == nil || !strings.Contains(err.Error(), "no //datlas:fixture types found") {
		t.Fatalf("unexpected error: %v", err)
	}
}

func TestMethodNameConflict(t *testing.T) {
	dir := testutil.WriteTree(t, map[string]string{
		"a/a.go": "package a\n\n//datlas:fixture\ntype User struct{}\n",
		"b/b.go": "package b\n\n//datlas:fixture\ntype User struct{}\n",
	})
	_, err := run(Config{Dir: dir, Patterns: []string{"./a", "./b"}, OutDir: "fx"})
	if err == nil || !strings.Contains(err.Error(), "factory method User for") {
		t.Fatalf("unexpected error: %v", err)
	}
}
