// Package loader loads Go packages and extracts datlas directives from them.
// It is shared by the fixture and declarative generators.
package loader

import (
	"errors"
	"fmt"
	"go/ast"
	"go/token"
	"go/types"
	"os"
	"strings"

	"golang.org/x/tools/go/packages"

	"github.com/moznion/go-datlas/internal/generator/output"
)

// DirectivePrefix introduces every datlas directive comment.
const DirectivePrefix = "//datlas:"

// Directive kinds.
const (
	KindFixture = "fixture"
	KindMaster  = "master"
	KindSeed    = "seed"
	KindEnum    = "enum"
)

var knownKinds = map[string]bool{KindFixture: true, KindMaster: true, KindSeed: true, KindEnum: true}

// Directive is a datlas directive attached to a type declaration.
type Directive struct {
	Kind string
	Args []string
	Pos  token.Position

	Package *packages.Package
	Type    *types.TypeName
	// Struct is the underlying struct type. It is nil for enum directives.
	Struct *types.Struct
}

// Load loads and type-checks the packages matched by patterns, resolved relative to dir.
//
// Files previously generated by datlas are replaced with an empty file while loading,
// so stale generated code never prevents regeneration. Because the rest of the package
// may reference those generated identifiers, type errors are tolerated here;
// callers must check that the types they use are valid (see CheckType).
func Load(dir string, patterns ...string) ([]*packages.Package, error) {
	// First pass: list files only, to find previously generated ones.
	listed, err := packages.Load(&packages.Config{
		Mode: packages.NeedName | packages.NeedFiles,
		Dir:  dir,
	}, patterns...)
	if err != nil {
		return nil, err
	}
	overlay := map[string][]byte{}
	for _, p := range listed {
		for _, f := range p.GoFiles {
			src, err := os.ReadFile(f)
			if err != nil {
				return nil, err
			}
			if output.IsGenerated(src) {
				overlay[f] = []byte("package " + p.Name + "\n")
			}
		}
	}

	pkgs, err := packages.Load(&packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo | packages.NeedModule,
		Dir:     dir,
		Overlay: overlay,
	}, patterns...)
	if err != nil {
		return nil, err
	}
	if len(pkgs) == 0 {
		return nil, fmt.Errorf("no packages matched %q", patterns)
	}
	var errs []error
	for _, p := range pkgs {
		for _, e := range p.Errors {
			// Type errors are tolerated (see above). Loading type information makes `go list`
			// compile the package, which reports the same errors again as compiler output.
			if e.Kind == packages.TypeError ||
				(e.Kind == packages.ListError && strings.HasPrefix(e.Msg, "# "+p.PkgPath+"\n")) {
				continue
			}
			errs = append(errs, e)
		}
	}
	if err := errors.Join(errs...); err != nil {
		return nil, err
	}
	return pkgs, nil
}

// PackagePaths returns the import paths of the packages matched by patterns, resolved relative to dir,
// without loading them.
func PackagePaths(dir string, patterns ...string) (map[string]bool, error) {
	listed, err := packages.Load(&packages.Config{Mode: packages.NeedName, Dir: dir}, patterns...)
	if err != nil {
		return nil, err
	}
	paths := map[string]bool{}
	for _, p := range listed {
		paths[p.PkgPath] = true
	}
	return paths, nil
}

// CheckType returns an error when t, or a type it is built from, failed to type-check.
// The error carries the type errors of pkg so the root cause is visible.
func CheckType(pkg *packages.Package, t types.Type, context string) error {
	if !containsInvalid(t, map[types.Type]bool{}) {
		return nil
	}
	msgs := []string{fmt.Sprintf("%s: type could not be resolved", context)}
	for _, e := range pkg.Errors {
		msgs = append(msgs, "\t"+e.Error())
	}
	return errors.New(strings.Join(msgs, "\n"))
}

func containsInvalid(t types.Type, seen map[types.Type]bool) bool {
	if seen[t] {
		return false
	}
	seen[t] = true
	switch t := t.(type) {
	case *types.Basic:
		return t.Kind() == types.Invalid
	case *types.Named:
		return containsInvalid(t.Underlying(), seen)
	case *types.Alias:
		return containsInvalid(types.Unalias(t), seen)
	case *types.Pointer:
		return containsInvalid(t.Elem(), seen)
	case *types.Slice:
		return containsInvalid(t.Elem(), seen)
	case *types.Array:
		return containsInvalid(t.Elem(), seen)
	case *types.Map:
		return containsInvalid(t.Key(), seen) || containsInvalid(t.Elem(), seen)
	case *types.Struct:
		for i := range t.NumFields() {
			if containsInvalid(t.Field(i).Type(), seen) {
				return true
			}
		}
	}
	return false
}

// Directives returns every datlas directive found in pkgs, in source order.
//
// A directive must be placed in the doc comment of a non-generic type declaration:
// a struct type for fixture, master and seed, and a string or integer type for enum.
// Directives placed anywhere else, and directives of unknown kinds, are reported as errors.
func Directives(pkgs []*packages.Package) ([]Directive, error) {
	var (
		result []Directive
		errs   []error
	)
	for _, pkg := range pkgs {
		for _, file := range pkg.Syntax {
			attached := map[*ast.Comment]bool{}
			for _, decl := range file.Decls {
				gd, ok := decl.(*ast.GenDecl)
				if !ok || gd.Tok != token.TYPE {
					continue
				}
				for _, spec := range gd.Specs {
					ts := spec.(*ast.TypeSpec)
					docs := []*ast.CommentGroup{ts.Doc}
					if len(gd.Specs) == 1 {
						docs = append(docs, gd.Doc)
					}
					for _, doc := range docs {
						for _, c := range directiveComments(doc) {
							attached[c] = true
							d, err := newDirective(pkg, ts, c)
							if err != nil {
								errs = append(errs, err)
								continue
							}
							result = append(result, d)
						}
					}
				}
			}
			for _, cg := range file.Comments {
				for _, c := range directiveComments(cg) {
					if !attached[c] {
						errs = append(errs, fmt.Errorf("%s: datlas directive must be placed on a type declaration",
							pkg.Fset.Position(c.Pos())))
					}
				}
			}
		}
	}
	return result, errors.Join(errs...)
}

func directiveComments(cg *ast.CommentGroup) []*ast.Comment {
	if cg == nil {
		return nil
	}
	var cs []*ast.Comment
	for _, c := range cg.List {
		if strings.HasPrefix(c.Text, DirectivePrefix) {
			cs = append(cs, c)
		}
	}
	return cs
}

func newDirective(pkg *packages.Package, ts *ast.TypeSpec, c *ast.Comment) (Directive, error) {
	pos := pkg.Fset.Position(c.Pos())
	fields := strings.Fields(strings.TrimPrefix(c.Text, DirectivePrefix))
	if len(fields) == 0 || !knownKinds[fields[0]] {
		return Directive{}, fmt.Errorf("%s: unknown datlas directive %q", pos, c.Text)
	}
	obj, ok := pkg.TypesInfo.Defs[ts.Name].(*types.TypeName)
	if !ok {
		return Directive{}, fmt.Errorf("%s: cannot resolve type %s", pos, ts.Name.Name)
	}
	if ts.TypeParams != nil {
		return Directive{}, fmt.Errorf("%s: %s: datlas directives cannot be used on generic types", pos, ts.Name.Name)
	}
	if fields[0] == KindEnum {
		if len(fields) > 1 {
			return Directive{}, fmt.Errorf("%s: //datlas:enum takes no arguments", pos)
		}
		b, ok := obj.Type().Underlying().(*types.Basic)
		if !ok || b.Info()&(types.IsString|types.IsInteger) == 0 || ts.Assign.IsValid() {
			return Directive{}, fmt.Errorf("%s: %s: //datlas:enum can only be used on defined string or integer types", pos, ts.Name.Name)
		}
		return Directive{Kind: KindEnum, Pos: pos, Package: pkg, Type: obj}, nil
	}
	st, ok := obj.Type().Underlying().(*types.Struct)
	if !ok {
		return Directive{}, fmt.Errorf("%s: %s: //datlas:%s can only be used on struct types", pos, ts.Name.Name, fields[0])
	}
	return Directive{
		Kind:    fields[0],
		Args:    fields[1:],
		Pos:     pos,
		Package: pkg,
		Type:    obj,
		Struct:  st,
	}, nil
}
